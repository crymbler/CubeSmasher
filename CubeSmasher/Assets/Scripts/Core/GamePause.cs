using UnityEngine;

/// <summary>
/// Ставит игру на паузу, пока открыто окно.
///
/// Счётчик, а не одиночный флаг. Окон несколько — магазин, гараж, скины,
/// настройки — и каждое включает паузу. С одиночным флагом закрытие одного
/// окна снимало паузу, хотя другое ещё открыто, либо наоборот: два открытия
/// при одном закрытии оставляли `Time.timeScale = 0` навсегда. Снаружи это
/// выглядело как «игра зависла» без единой ошибки в консоли.
///
/// Счётчик держит паузу, пока открыто хоть одно окно, и снимает её, когда
/// закрылось последнее.
/// </summary>
public class GamePause
{
    private int _depth;

    /// <summary>Сколько окон сейчас требуют паузы. Для отладки и проверок.</summary>
    public int Depth => _depth;

    /// <summary>Открылось окно: поставить на паузу.</summary>
    public void Enable()
    {
        _depth++;
        Time.timeScale = 0f;
    }

    /// <summary>Закрылось окно: снять паузу, если закрылось последнее.</summary>
    public void Disable()
    {
        // Счётчик не должен уходить в минус: иначе после лишнего закрытия
        // пауза не снимется уже никогда, и следующий Enable её не восстановит
        if (_depth > 0) _depth--;

        if (_depth == 0) Time.timeScale = 1f;
    }

    /// <summary>Сбросить состояние. Нужно при перезагрузке сцены.</summary>
    public void Reset()
    {
        _depth = 0;
        Time.timeScale = 1f;
    }
}
