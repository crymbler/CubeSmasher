namespace CubeSmasher.Core.Interfaces
{
    /// <summary>
    /// Три состояния машины в гараже.
    /// Locked    — стадия не пройдена. Видна плашка "Откроется на стадии N", модели нет.
    /// Available — стадия пройдена, игрок ещё не нажал "Открыть". Модель видна, но без
    ///             описания, характеристик и дохода.
    /// Opened    — игрок открыл машину. Видно описание и характеристики, доход начисляется.
    /// </summary>
    public enum GarageCarState
    {
        Locked = 0,
        Available = 1,
        Opened = 2
    }
}
